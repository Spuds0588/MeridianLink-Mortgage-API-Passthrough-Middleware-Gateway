#!/usr/bin/env node
"use strict";

/**
 * Builds dist/gateway.js (single CommonJS bundle) and inlines it into the
 * deployable template.yaml from infra/template.yaml.
 *
 * Usage: node scripts/build.js [--check]
 *   --check  fail if the committed template.yaml is out of date
 */

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "src");
const entry = "lambda.js";
const sourcePath = path.join(root, "infra", "template.yaml");
const outputPath = path.join(root, "template.yaml");
const distPath = path.join(root, "dist", "gateway.js");
const PLACEHOLDER = /^[ \t]*\/\/__GATEWAY_CODE__$/m;
const INDENT = " ".repeat(9);
const LIMIT_BYTES = 51200;

function bundle(entryId) {
  const modules = new Map();
  const visit = (id) => {
    if (modules.has(id)) return;
    const file = path.join(srcDir, id);
    const source = fs.readFileSync(file, "utf8");
    modules.set(id, source);
    for (const match of source.matchAll(/require\(["'](\.[^"']+)["']\)/g)) {
      const resolved = `${match[1].replace(/^\.\//, "").replace(/\.js$/, "")}.js`;
      visit(resolved);
    }
  };
  visit(entryId);

  const definitions = [...modules.entries()]
    .map(([id, source]) => `  ${JSON.stringify(id)}: (module, exports, require) => {\n${source}\n  },`)
    .join("\n");

  return `// Generated by scripts/build.js — do not edit.
"use strict";
const __nativeRequire = require;
const __defs = {
${definitions}
};
const __cache = {};
function __require(id) {
  if (__cache[id]) return __cache[id].exports;
  if (!__defs[id]) throw new Error("Module not bundled: " + id);
  const module = (__cache[id] = { exports: {} });
  __defs[id](module, module.exports, (spec) =>
    spec.startsWith(".") ? __require(spec.replace(/^\\.\\//, "").replace(/\\.js$/, "") + ".js") : __nativeRequire(spec)
  );
  return module.exports;
}
module.exports = __require(${JSON.stringify(entryId)});
`;
}

const code = bundle(entry);
const source = fs.readFileSync(sourcePath, "utf8");
if (!PLACEHOLDER.test(source)) throw new Error(`${sourcePath} is missing the //__GATEWAY_CODE__ placeholder`);

// The deploy copy drops comments, leading indentation, and blank lines to fit
// CloudFormation's 51,200-byte direct-upload limit. dist/gateway.js keeps the
// readable form.
const stripComments = (source) => {
  const lines = [];
  let inBlock = false;
  for (const line of source.split("\n")) {
    const trimmed = line.trim();
    if (inBlock) {
      if (trimmed.endsWith("*/")) inBlock = false;
      continue;
    }
    if (trimmed.startsWith("//")) continue;
    if (trimmed.startsWith("/*")) {
      inBlock = !trimmed.endsWith("*/");
      continue;
    }
    lines.push(line);
  }
  return lines;
};

const inlined = stripComments(code)
  .map((line) => line.replace(/^[ \t]+/, ""))
  .filter((line) => line.length > 0)
  .map((line) => INDENT + line)
  .join("\n");

const rendered = source.replace(PLACEHOLDER, () => inlined);
const bytes = Buffer.byteLength(rendered);
if (bytes > LIMIT_BYTES) throw new Error(`template.yaml would be ${bytes} bytes, over CloudFormation's ${LIMIT_BYTES}-byte limit`);

fs.mkdirSync(path.dirname(distPath), { recursive: true });
fs.writeFileSync(distPath, code);

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== rendered) {
    console.error("template.yaml is stale. Run: npm run build");
    process.exit(1);
  }
  console.log(`template.yaml is up to date (${bytes} bytes)`);
} else {
  fs.writeFileSync(outputPath, rendered);
  console.log(`Wrote dist/gateway.js (${Buffer.byteLength(code)} bytes) and template.yaml (${bytes} bytes)`);
}
